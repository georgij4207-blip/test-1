"""Optional: double the frame rate to a 5° step with optical-flow in-betweens.

Every generated frame is marked "interpolated": true and gets a confidence
score derived from how similar its two neighbours are. Pairs flagged as a
"jump" in the 10° set (different drawings, e.g. profile -> back view) give
low-confidence in-betweens that look like a cross-dissolve; they are kept so
the timing stays even, but they are NOT verified drawings.

Run after build_frames.py:  python3 tools/interpolate.py
"""
import json
import os
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(__file__))
from morph import flow_morph  # noqa: E402

ASSETS = "web/assets"


def main():
    with open(f"{ASSETS}/manifest.json", encoding="utf-8") as fh:
        base = json.load(fh)
    fw, fh_, n = base["frameWidth"], base["frameHeight"], base["count"]
    frames = [np.asarray(Image.open(f"{ASSETS}/frames/coyote_{i * 10:03d}.png").convert("RGBA"))
              for i in range(n)]
    out, info = [], []
    for i in range(n):
        a, b = frames[i], frames[(i + 1) % n]
        src = base["frames"][i]
        out.append(a)
        info.append({"angle": i * 10, "source": src["source"], "interpolated": src["interpolated"]})
        mid = flow_morph(a, b, 0.5)
        iou = src["to_next"]["iou"]
        conf = "высокая" if iou >= 0.8 else "средняя" if iou >= 0.7 else "низкая"
        out.append(mid)
        info.append({"angle": i * 10 + 5, "interpolated": True, "confidence": conf,
                     "source": f"оптический поток {i * 10}°↔{(i * 10 + 10) % 360}° (не проверено)"})
        print(f"{i * 10 + 5:3d}°  neighbour IoU {iou:.3f} -> confidence {conf}")

    cols = 9
    rows = (len(out) + cols - 1) // cols
    sprite = Image.new("RGBA", (fw * cols, fh_ * rows), (0, 0, 0, 0))
    for k, img in enumerate(out):
        sprite.paste(Image.fromarray(img, "RGBA"), ((k % cols) * fw, (k // cols) * fh_))
    sprite.save(f"{ASSETS}/coyote_sprite_5deg.png", optimize=True)

    manifest = dict(base, columns=cols, count=len(out), stepDegrees=5,
                    sprite="assets/coyote_sprite_5deg.png", frames=info)
    with open(f"{ASSETS}/manifest_5deg.json", "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, ensure_ascii=False, indent=1)
    write_js()


def write_js():
    """Bundle the manifests as a script so index.html also works from file://."""
    data = {}
    for key, name in (("10", "manifest.json"), ("5", "manifest_5deg.json")):
        p = f"{ASSETS}/{name}"
        if os.path.exists(p):
            with open(p, encoding="utf-8") as fh:
                data[key] = json.load(fh)
    with open(f"{ASSETS}/manifest.js", "w", encoding="utf-8") as fh:
        fh.write("// Generated by tools/build_frames.py / tools/interpolate.py. Do not edit.\n")
        fh.write("window.COYOTE_MANIFESTS = " + json.dumps(data, ensure_ascii=False) + ";\n")


if __name__ == "__main__":
    main()
